import React, { useState } from 'react';
import { X, Download, Folder, FileCode, CheckCircle2, Copy, Check } from 'lucide-react';
import { ModernizationResult } from '../data/modernizationEngine';

interface ExportSolutionModalProps {
  isOpen: boolean;
  onClose: () => void;
  result: ModernizationResult;
}

export const ExportSolutionModal: React.FC<ExportSolutionModalProps> = ({
  isOpen,
  onClose,
  result,
}) => {
  const [copiedFile, setCopiedFile] = useState<string | null>(null);

  if (!isOpen) return null;

  const solutionFiles = [
    {
      path: 'Contoso.Modernization.sln',
      type: 'solution',
      desc: 'Visual Studio / .NET 9 Solution File',
      content: `Microsoft Visual Studio Solution File, Format Version 12.00
# Visual Studio Version 17
VisualStudioVersion = 17.12.35527.113
MinimumVisualStudioVersion = 10.0.40219.1
Project("{9A19103F-16F7-4668-BE54-9A1E7A4F7556}") = "Contoso.Billing.API", "src\\Contoso.Billing.API\\Contoso.Billing.API.csproj", "{A1111111-1111-1111-1111-111111111111}"
EndProject
Project("{9A19103F-16F7-4668-BE54-9A1E7A4F7556}") = "Contoso.Billing.Application", "src\\Contoso.Billing.Application\\Contoso.Billing.Application.csproj", "{B2222222-2222-2222-2222-222222222222}"
EndProject
Project("{9A19103F-16F7-4668-BE54-9A1E7A4F7556}") = "Contoso.Billing.Domain", "src\\Contoso.Billing.Domain\\Contoso.Billing.Domain.csproj", "{C3333333-3333-3333-3333-333333333333}"
EndProject
Project("{9A19103F-16F7-4668-BE54-9A1E7A4F7556}") = "Contoso.Billing.Infrastructure", "src\\Contoso.Billing.Infrastructure\\Contoso.Billing.Infrastructure.csproj", "{D4444444-4444-4444-4444-444444444444}"
EndProject
Project("{9A19103F-16F7-4668-BE54-9A1E7A4F7556}") = "Contoso.Billing.UnitTests", "tests\\Contoso.Billing.UnitTests\\Contoso.Billing.UnitTests.csproj", "{E5555555-5555-5555-5555-555555555555}"
EndProject`
    },
    ...result.refactoredFiles.map(rf => ({
      path: rf.path,
      type: 'csharp',
      desc: rf.description,
      content: rf.code
    })),
    {
      path: 'src/Contoso.Billing.Infrastructure/DependencyInjection.cs',
      type: 'csharp',
      desc: 'Microsoft.Extensions.DependencyInjection Registrations',
      content: result.uncoupling.serviceRegistrationCode
    },
    {
      path: 'tests/Contoso.Billing.UnitTests/Commands/ProcessOrderCommandHandlerTests.cs',
      type: 'test',
      desc: 'xUnit Regression Safety Tests with Moq Mocks',
      content: result.testSuite.testCode
    },
    {
      path: 'migrations/20261031_DecomposeOrdersTable.sql',
      type: 'sql',
      desc: 'Idempotent SQL Server DDL Migration Script',
      content: result.schemaMigration.sqlMigrationScript
    }
  ];

  const handleCopy = (path: string, content: string) => {
    navigator.clipboard.writeText(content);
    setCopiedFile(path);
    setTimeout(() => setCopiedFile(null), 2000);
  };

  const handleDownloadAll = () => {
    // Combine all files into a structured downloadable solution manifest
    let fullManifest = `// ================================================================\n// CONTOSO BILLING MODERNIZATION - CLEAN ARCHITECTURE .NET 9 PACKAGE\n// Generated by Meta Llama 3 Enterprise Modernization Copilot\n// ================================================================\n\n`;
    
    solutionFiles.forEach(f => {
      fullManifest += `\n// ================================================================\n// FILE: ${f.path}\n// ================================================================\n\n${f.content}\n\n`;
    });

    const blob = new Blob([fullManifest], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `${result.systemId}_dotnet9_clean_architecture.txt`;
    link.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="fixed inset-0 z-50 bg-slate-950/80 backdrop-blur-sm flex items-center justify-center p-4">
      <div className="bg-slate-900 border border-slate-800 rounded-xl max-w-4xl w-full max-h-[90vh] flex flex-col shadow-2xl overflow-hidden">
        {/* Header */}
        <div className="p-4 border-b border-slate-800 flex items-center justify-between">
          <div className="flex items-center gap-2">
            <Folder className="w-4 h-4 text-cyan-400" />
            <h3 className="text-sm font-semibold text-white">
              Export Clean Architecture .NET 9 Solution Package
            </h3>
          </div>
          <button
            onClick={onClose}
            className="p-1 text-slate-400 hover:text-white rounded transition-colors"
          >
            <X className="w-4 h-4" />
          </button>
        </div>

        {/* Content list */}
        <div className="p-5 overflow-y-auto space-y-3 flex-1">
          <div className="text-xs text-slate-400 mb-2">
            The following decoupled components have been generated according to DDD and Clean Architecture standards:
          </div>

          <div className="divide-y divide-slate-800 border border-slate-800 rounded-lg overflow-hidden bg-slate-950">
            {solutionFiles.map((f) => (
              <div key={f.path} className="p-3.5 flex items-center justify-between hover:bg-slate-900/60 transition-colors">
                <div className="space-y-0.5">
                  <div className="text-xs font-mono text-cyan-300 font-medium flex items-center gap-2">
                    <FileCode className="w-3.5 h-3.5 text-slate-500" />
                    <span>{f.path}</span>
                  </div>
                  <div className="text-[11px] text-slate-500 font-sans">
                    {f.desc}
                  </div>
                </div>

                <button
                  onClick={() => handleCopy(f.path, f.content)}
                  className="flex items-center gap-1.5 px-2.5 py-1 text-xs text-slate-400 hover:text-white bg-slate-900 border border-slate-800 rounded transition-colors shrink-0 font-mono"
                >
                  {copiedFile === f.path ? <Check className="w-3 h-3 text-emerald-400" /> : <Copy className="w-3 h-3" />}
                  <span>{copiedFile === f.path ? 'Copied' : 'Copy'}</span>
                </button>
              </div>
            ))}
          </div>
        </div>

        {/* Footer */}
        <div className="p-4 border-t border-slate-800 bg-slate-950 flex items-center justify-between">
          <div className="text-xs text-slate-500 font-mono">
            {solutionFiles.length} enterprise files generated · Zero compiler warnings
          </div>
          <div className="flex items-center gap-2">
            <button
              onClick={onClose}
              className="px-3.5 py-1.5 text-xs text-slate-400 hover:text-white rounded transition-colors"
            >
              Close
            </button>
            <button
              onClick={handleDownloadAll}
              className="flex items-center gap-1.5 px-4 py-1.5 text-xs font-semibold bg-cyan-500 hover:bg-cyan-400 text-slate-950 rounded-lg transition-colors font-bold"
            >
              <Download className="w-3.5 h-3.5" />
              <span>Download Solution Bundle</span>
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
